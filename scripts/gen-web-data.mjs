// Writes web/data.js from devnet.json and a live read of the devnet vault, so the design shows real values only.
// The RPC URL stays in .env.devnet and is never written to the site.
import fs from 'node:fs';
import { Connection, PublicKey } from '@solana/web3.js';
import { RULES, fetchVault } from '../sdk/index.mjs';

const st = JSON.parse(fs.readFileSync('devnet.json'));
const env = Object.fromEntries(fs.readFileSync('.env.devnet', 'utf8').trim().split('\n').map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
const c = new Connection(env.METBOI_RPC, 'confirmed');
const v = await fetchVault(c, st.vault);
const meter = (m) => ({ txCap: m.txCap.toString(), dailyCap: m.dailyCap.toString(), spent: m.spent.toString() });
const tokens = await c.getParsedTokenAccountsByOwner(new PublicKey(st.wallet), { programId: new PublicKey('TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA') });
const time = async (sig) => (await c.getTransaction(sig, { maxSupportedTransactionVersion: 1, commitment: 'confirmed' }))?.blockTime ?? null;
const events = {};
for (const name of ['vault_initialize', 'agent_dlmm_swap', 'agent_damm_swap', 'agent_dlmm_open', 'agent_dlmm_close', 'owner_pause', 'owner_resume']) {
  const signature = st.txs[name].split(',')[0];
  events[name] = { signature, time: await time(signature) };
}
const VENUES = { [RULES.DLMM.programId]: 'DLMM', [RULES.DAMM_V2.programId]: 'DAMM v2', [RULES.DBC.programId]: 'DBC' };
const PAIRS = { [st.dlmmPool]: 'TEST / wSOL', [st.dammPool]: 'TEST / wSOL', ...(st.tools?.dbc_launch ? { [st.tools.dbc_launch.pool]: 'MBOI / wSOL' } : {}) };
async function describePools(pools) {
  const infos = await c.getMultipleAccountsInfo(pools);
  return pools.map((p, i) => ({ venue: VENUES[infos[i]?.owner.toBase58()] ?? 'Unknown', address: p.toBase58(), pair: PAIRS[p.toBase58()] ?? 'Unknown' }));
}
const data = {
  readAt: new Date().toISOString(),
  program: st.program, vault: st.vault, wallet: st.wallet, owner: st.owner, agent: st.agent, testMint: st.mint,
  pools: await describePools(v.pools),
  tokenNames: { [st.mint]: 'TEST', ...(st.tools?.dbc_launch ? { [st.tools.dbc_launch.mint]: 'MBOI' } : {}) },
  paused: v.paused, actions: v.actions, agentExpiresAt: v.agentExpiresAt,
  lamports: await c.getBalance(new PublicKey(st.wallet)), lamportMeter: meter(v.lamports),
  budgets: v.budgets.map((b) => ({ mint: b.mint.toBase58(), ...meter(b) })),
  balances: tokens.value.map((t) => ({ mint: t.account.data.parsed.info.mint, amount: t.account.data.parsed.info.tokenAmount.amount, decimals: t.account.data.parsed.info.tokenAmount.decimals })),
  events,
};
fs.writeFileSync('web/data.js', `// Generated by scripts/gen-web-data.mjs. Real devnet values, read at ${data.readAt}.\nwindow.DEVNET = ${JSON.stringify(data, null, 1)};\n`);
console.log('wrote web/data.js');
process.exit(0);
